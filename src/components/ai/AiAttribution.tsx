export function AiAttribution({ model, at }: { model: string; at: Date | string }) {
  const date = typeof at === "string" ? new Date(at) : at;
  return (
    <p className="text-xs text-[var(--color-text-faint)]">
      Generated by {model} &middot; {date.toLocaleString("en-NG", { dateStyle: "medium", timeStyle: "short" })} &middot; review before relying on it
    </p>
  );
}
